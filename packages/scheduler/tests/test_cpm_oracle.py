"""Both CPM engines checked against an independent reference, not each other (#3987).

``test_wasm_conformance.py`` and ``packages/wasm-scheduler/tests/conformance.rs``
compare the Python and Rust engines through snapshots *generated by the Python
engine*, so they prove parity, not correctness: one fixture snapshot
(``milestone_tasks.json``) encoded a wrong rule both engines agreed on (#4079).
This module holds both engines to :mod:`tests.oracle.reference_cpm`, a slow
reference written from the documented CPM math, over Hypothesis-generated DAGs.

What is compared, exactly
-------------------------
* A task with work (``duration >= 1``): ``early_start`` and ``early_finish``,
  always. ``late_start``, ``late_finish``, ``total_float``, ``free_float`` and
  ``is_critical`` too, unless a milestone lies downstream of it or a milestone
  decides the project finish — then they depend on which edge of its day that
  milestone is *shown* on (#4174, #4183), a display convention the reference does
  not model (``RefTask.late_stated``). On a network with no milestones every one
  of these fields is compared on every task.
* A milestone (``duration == 0``): only its early **working-time position** — the
  shown day folded with ``milestone_at_day_end`` (the end of day ``D`` is the same
  position as the start of the next working day, #4178/#4207). Which of the two
  days it is shown on, its late dates, and its floats are not compared.
* Not compared at all: ``scheduled_start``, ``critical_path``, ``driving_edges``,
  ``project_finish`` (implied by the per-task dates), and Monte Carlo, which the
  Rust engine does not implement.
* Not generated: progress/actuals, the data date, ``planned_start``, per-task
  calendars, summary tasks. And two link shapes where both engines disagree with
  the reference, excluded until they are triaged — see :func:`_known_divergent`
  and TODO(#4272)/TODO(#4273).

The Rust side runs in two ways. The Hypothesis properties drive a native build of
the crate's ``oracle_runner`` example over stdin when ``cargo`` (or a prebuilt
runner named by ``TRUEPPM_ORACLE_RUST_RUNNER``) is available, and skip otherwise —
the ``scheduler:*`` CI image has no Rust toolchain. CI instead checks Rust against
a committed, seeded corpus generated *by the reference*
(``packages/wasm-scheduler/fixtures/oracle/corpus.json``), asserted by
``packages/wasm-scheduler/tests/oracle_conformance.rs`` under ``wasm:test``; the
corpus tests below keep that file in lock-step with the reference and check the
Python engine against it too. Regenerate with
``REGEN_ORACLE_CORPUS=1 pytest tests/test_cpm_oracle.py -k corpus``.
"""

