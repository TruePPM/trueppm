@dataclass(frozen=True)
class EngineTask:
    early_start: date
    early_finish: date
    late_start: date
    late_finish: date
    total_float: int  # working days
    free_float: int
    is_critical: bool
    milestone_at_day_end: bool


def _whole_days(seconds: float) -> int:
    assert seconds % 86400 == 0, seconds
    return int(seconds // 86400)


def python_engine(project: RefProject) -> dict[str, EngineTask]:
    return python_engine_tasks(schedule(to_engine_project(project)))


def python_engine_tasks(result: ScheduleResult) -> dict[str, EngineTask]:
    return {
        t.id: EngineTask(
            early_start=t.early_start,
            early_finish=t.early_finish,
            late_start=t.late_start,
            late_finish=t.late_finish,
            total_float=_whole_days(t.total_float.total_seconds()),
            free_float=_whole_days(t.free_float.total_seconds()),
            is_critical=t.is_critical,
            milestone_at_day_end=t.milestone_at_day_end,
        )
        for t in result.tasks
    }


def _engine_task_from_json(row: dict[str, Any]) -> EngineTask:
    return EngineTask(
        early_start=date.fromisoformat(row["early_start"]),
        early_finish=date.fromisoformat(row["early_finish"]),
        late_start=date.fromisoformat(row["late_start"]),
        late_finish=date.fromisoformat(row["late_finish"]),
        total_float=_whole_days(row["total_float"]),
        free_float=_whole_days(row["free_float"]),
        is_critical=row["is_critical"],
        milestone_at_day_end=row.get("milestone_at_day_end", False),
    )


