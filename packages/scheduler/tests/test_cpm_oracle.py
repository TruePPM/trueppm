@st.composite
def networks_with_an_fs_link(draw: st.DrawFn) -> tuple[RefProject, RefLink]:
    """A network of work, and one FS link ``A -> B`` in it to split."""
    project = draw(ref_projects(milestones=False))
    n = len(project.durations)
    if n < 2:
        project = replace(project, durations={**project.durations, "T1": 2})
        n = 2
    j = draw(st.integers(1, n - 1))
    i = draw(st.integers(0, j - 1))
    link = RefLink(f"T{i}", f"T{j}", "FS", draw(st.integers(-4, 6)))
    # One link per ordered pair: replace whatever A -> B carried with the FS link.
    others = tuple(ln for ln in project.links if (ln.pred, ln.succ) != (link.pred, link.succ))
    return replace(project, links=(*others, link)), link


def _split_with_milestone(project: RefProject, link: RefLink) -> RefProject:
    """``A -FS(l)-> B`` becomes ``A -FS(0)-> M -FS(l)-> B``."""
    links = (
        *(ln for ln in project.links if ln != link),
        RefLink(link.pred, "M", "FS", 0),
        RefLink("M", link.succ, "FS", link.lag),
    )
    return replace(project, durations={**project.durations, "M": 0}, links=links)


def _unchanged_except_free_float_of(
    before: dict[str, EngineTask], after: dict[str, EngineTask], tid_with_new_successor: str
) -> None:
    """Every original task keeps every field; the one that gained a milestone
    successor may change only its free float, which is read on that milestone's
    shown day (scheduler.md, the free_float note)."""
    for tid, t in before.items():
        u = after[tid]
        if tid == tid_with_new_successor:
            u = replace(u, free_float=t.free_float)
        assert u == t, tid


def _assert_milestone_on_finish_of(
    after: dict[str, EngineTask], project: RefProject, a: str, m: str
) -> None:
    """``m`` sits on ``a``'s early finish, compared in working time (#4207).

    When ``a`` finishes after the project start, ``m`` is shown at the end of
    ``a``'s finish day exactly. An SF-only ``a`` can finish before the project
    start (#4218); ``m`` is then shown at the project start (#4225).
    """
    ref = reference_schedule(project)
    finish_at = ref.tasks[a].finish_at
    shown_at = max(finish_at, ref.project_start_at)
    cal = project.calendar
    expected = position_of(shown_at, ref.project_start_at, cal)
    assert engine_milestone_position(after[m], ref, cal) == expected
    if finish_at > ref.project_start_at:
        assert after[m].early_start == after[a].early_finish
        assert after[m].milestone_at_day_end


@pytest.mark.fuzz
@given(networks_with_an_fs_link())
def test_inserting_a_milestone_into_an_fs_link_moves_nothing(
    case: tuple[RefProject, RefLink],
) -> None:
    """``A -FS(l)-> B`` vs ``A -FS(0)-> M -FS(l)-> B``: nothing moves; ``M`` sits on A's EF.

    Every original task keeps every compared field (A's free float aside), and the
    reference agrees on both networks, so this is not a property only the engine's
    own conventions satisfy.
    """
    project, link = case
    split = _split_with_milestone(project, link)
    before, after = python_engine(project), python_engine(split)
    _unchanged_except_free_float_of(before, after, link.pred)
    _assert_milestone_on_finish_of(after, split, link.pred, "M")
    assert_matches_reference(before, project)
    assert_matches_reference(after, split)


@pytest.mark.fuzz
@given(ref_projects(milestones=True), st.data())
def test_a_start_milestone_at_project_start_delays_nothing(
    project: RefProject, data: st.DataObject
) -> None:
    """``S -FS(0)->`` any task with work that is not SF-only changes nothing at all.

    Excluded on purpose, as documented behavior rather than a delay: an SF-only
    task, which any FS link returns to the project-start floor (#4218); and a
    milestone, whose links count from its raw instant even before the project
    start (#4225), so a link from ``S`` would hold it there.
    """
    assume(not _known_divergent(project))
    eligible = sorted(
        tid
        for tid, n in project.durations.items()
        if n > 0
        and not (
            (inc := [ln for ln in project.links if ln.succ == tid])
            and all(ln.kind == "SF" for ln in inc)
        )
    )
    assume(eligible)
    targets = data.draw(st.lists(st.sampled_from(eligible), unique=True, min_size=1))
    with_start = replace(
        project,
        durations={"S": 0, **project.durations},
        links=project.links + tuple(RefLink("S", t, "FS", 0) for t in targets),
    )
    before, after = python_engine(project), python_engine(with_start)
    for tid, t in before.items():
        assert after[tid] == t, tid
    assert_matches_reference(after, with_start)


@pytest.mark.fuzz
@given(ref_projects(milestones=True))
def test_every_task_with_work_spans_exactly_its_duration(project: RefProject) -> None:
    """``EF - ES + 1 == duration`` in working days, for every non-milestone task."""
    cal = project.calendar
    engine = python_engine(project)
    ref = reference_schedule(project)
    for tid, n in project.durations.items():
        if n == 0:
            continue
        got = engine[tid]
        span = working_days_between(got.early_start, got.early_finish + timedelta(days=1), cal)
        assert span == n, tid
        late = working_days_between(got.late_start, got.late_finish + timedelta(days=1), cal)
        assert late == n, tid
        want = ref.tasks[tid]
        assert working_days_between(want.start_at, want.finish_at, cal) == n, tid


@pytest.mark.fuzz
@given(ref_projects(milestones=False), st.data())
def test_a_zero_day_fs_milestone_is_time_neutral(project: RefProject, data: st.DataObject) -> None:
    """Hanging ``A -FS(0)-> M`` off any task moves no other task (#4079).

    Before #4079 a milestone took a working day, so this moved the project finish
    whenever ``A`` was on the critical path.
    """
    anchor = data.draw(st.sampled_from(sorted(project.durations)))
    with_m = replace(
        project,
        durations={**project.durations, "M": 0},
        links=(*project.links, RefLink(anchor, "M", "FS", 0)),
    )
    before, after = python_engine(project), python_engine(with_m)
    _unchanged_except_free_float_of(before, after, anchor)
    _assert_milestone_on_finish_of(after, with_m, anchor, "M")
    assert_matches_reference(after, with_m)


