_EPOCH = date(2026, 1, 5)  # a Monday


@st.composite
def ref_calendars(draw: st.DrawFn) -> RefCalendar:
    mask = draw(st.one_of(st.just(MON_TO_FRI), st.integers(1, 0b1111111)))
    ranges = []
    for _ in range(draw(st.integers(0, 2))):
        lo = _EPOCH + timedelta(days=draw(st.integers(0, 40)))
        ranges.append((lo, lo + timedelta(days=draw(st.integers(0, 2)))))
    return RefCalendar(working_mask=mask, exceptions=tuple(ranges))


@st.composite
def ref_projects(draw: st.DrawFn, milestones: bool = True, max_tasks: int = 7) -> RefProject:
    """A random DAG: edges only run from a lower to a higher index, so no cycles."""
    n = draw(st.integers(1, max_tasks))
    low = 0 if milestones else 1
    durations = {f"T{i}": draw(st.integers(low, 6)) for i in range(n)}
    links = []
    for j in range(n):
        for i in range(j):
            if draw(st.integers(0, 2)) == 0:
                links.append(
                    RefLink(
                        pred=f"T{i}",
                        succ=f"T{j}",
                        kind=draw(st.sampled_from(LINK_TYPES)),
                        lag=draw(st.integers(-4, 6)),
                    )
                )
    return RefProject(
        start=_EPOCH + timedelta(days=draw(st.integers(0, 9))),
        durations=durations,
        links=tuple(links),
        calendar=draw(ref_calendars()),
    )


def random_ref_project(rng: random.Random) -> RefProject:
    """The corpus generator: the same shape as :func:`ref_projects`, from a seeded RNG."""
    n = rng.randint(1, 8)
    durations = {f"T{i}": (0 if rng.random() < 0.2 else rng.randint(1, 6)) for i in range(n)}
    links = tuple(
        RefLink(f"T{i}", f"T{j}", rng.choice(LINK_TYPES), rng.randint(-4, 6))
        for j in range(n)
        for i in range(j)
        if rng.random() < 0.35
    )
    mask = MON_TO_FRI if rng.random() < 0.6 else rng.randint(1, 0b1111111)
    ranges = []
    for _ in range(rng.randint(0, 2)):
        lo = _EPOCH + timedelta(days=rng.randint(0, 40))
        ranges.append((lo, lo + timedelta(days=rng.randint(0, 2))))
    return RefProject(
        start=_EPOCH + timedelta(days=rng.randint(0, 9)),
        durations=durations,
        links=links,
        calendar=RefCalendar(working_mask=mask, exceptions=tuple(ranges)),
    )


def _known_divergent(project: RefProject) -> bool:
    """Networks where both engines disagree with the reference — reported, unfixed.

    * TODO(#4272): a lagged FF or SF link *into* a milestone: the engines snap
      the milestone as if it were a task's finish, onto the end of a working
      day, so it can sit one working day after the same link written as FS.
      ``A(5d, Mon-Fri) -FF+1d-> M -FS-> C(1d)`` starts ``C`` on Tuesday; with
      ``-FS+1d->`` it starts Monday.
    * TODO(#4273): an FF link *out of* a milestone: the engines anchor it on
      the end of the working day before a start-of-day milestone rather than
      on its instant, so a later lag is absorbed by the weekend.
      ``M0(held at project start, Mon) -FF-> M1 -FS+1d-> T(1d)`` starts ``T``
      on Monday; with ``M0 -FS-> M1`` it starts Tuesday.

    For a zero-duration task start and finish are one instant, so in both cases
    FS and FF must agree; the reference has them agree, the engines do not.
    """
    is_milestone = {tid: n == 0 for tid, n in project.durations.items()}
    return any(
        (link.kind == "FF" and is_milestone[link.pred])  # TODO(#4273)
        or (link.lag != 0 and link.kind in ("FF", "SF") and is_milestone[link.succ])  # TODO(#4272)
        for link in project.links
    )


