def _expected_row(project: RefProject, ref: RefResult, tid: str) -> dict[str, Any]:
    """What ``oracle_conformance.rs`` asserts for one task, from the reference alone."""
    want = ref.tasks[tid]
    cal = project.calendar
    if want.is_milestone:
        # Either shown reading of the reference instant is accepted: the start of
        # the first working day at or after it, or the end of the working day
        # before that one — the same working-time position (#4178, #4207).
        assert want.shown_at is not None
        day = first_working_on_or_after(want.shown_at, cal)
        prior = last_working_on_or_before(day - timedelta(days=1), cal)
        return {"milestone_shown": [[day.isoformat(), False], [prior.isoformat(), True]]}
    row: dict[str, Any] = {
        "early_start": want.early_start.isoformat(),
        "early_finish": want.early_finish.isoformat(),
    }
    if want.late_stated:
        row |= {
            "late_start": want.late_start.isoformat(),
            "late_finish": want.late_finish.isoformat(),
            "total_float_days": want.total_float,
            "free_float_days": want.free_float,
        }
    return row


def build_corpus() -> dict[str, Any]:
    rng = random.Random(CORPUS_SEED)
    cases = []
    for k in range(CORPUS_SIZE):
        project = random_ref_project(rng)
        while _known_divergent(project):
            project = random_ref_project(rng)
        ref = reference_schedule(project)
        cases.append(
            {
                "name": f"case_{k:03d}",
                "project": project_document(project),
                "expected": {tid: _expected_row(project, ref, tid) for tid in project.durations},
            }
        )
    return {
        "_comment": (
            "Generated by the independent reference CPM (packages/scheduler/tests/oracle/"
            "reference_cpm.py), NOT by either engine (#3987). Regenerate with "
            "REGEN_ORACLE_CORPUS=1 pytest packages/scheduler/tests/test_cpm_oracle.py -k corpus"
        ),
        "seed": CORPUS_SEED,
        "cases": cases,
    }


def _load_corpus() -> dict[str, Any]:
    if not CORPUS_PATH.is_file():
        if IN_MONOREPO:
            pytest.fail(
                f"oracle corpus missing at {CORPUS_PATH}; regenerate with REGEN_ORACLE_CORPUS=1"
            )
        pytest.skip(f"oracle corpus not found at {CORPUS_PATH} (outside the monorepo)")
    with open(CORPUS_PATH) as f:
        loaded: dict[str, Any] = json.load(f)
    return loaded


def _corpus_text(corpus: dict[str, Any]) -> str:
    """One case per line, so a regenerated corpus diffs case by case."""
    head = {k: v for k, v in corpus.items() if k != "cases"}
    lines = [json.dumps(case, sort_keys=True) for case in corpus["cases"]]
    return json.dumps(head, sort_keys=True)[:-1] + ', "cases": [\n' + ",\n".join(lines) + "\n]}\n"


def test_corpus_is_what_the_reference_generates() -> None:
    """The committed corpus cannot drift from the reference that generated it."""
    fresh = _corpus_text(build_corpus())
    if REGEN_CORPUS:
        CORPUS_PATH.parent.mkdir(exist_ok=True)
        CORPUS_PATH.write_text(fresh)
    _load_corpus()  # skips outside the monorepo
    assert CORPUS_PATH.read_text() == fresh, (
        "fixtures/oracle/corpus.json is stale; regenerate with REGEN_ORACLE_CORPUS=1"
    )


def _corpus_row_mismatches(row: dict[str, Any], got: EngineTask) -> list[str]:
    if "milestone_shown" in row:
        shown = [got.early_start.isoformat(), got.milestone_at_day_end]
        return [] if shown in row["milestone_shown"] else [f"milestone shown {shown}"]
    actual = {
        "early_start": got.early_start.isoformat(),
        "early_finish": got.early_finish.isoformat(),
        "late_start": got.late_start.isoformat(),
        "late_finish": got.late_finish.isoformat(),
        "total_float_days": got.total_float,
        "free_float_days": got.free_float,
    }
    return [f"{k} {actual[k]} != {v}" for k, v in row.items() if actual[k] != v]


def test_python_engine_matches_the_oracle_corpus() -> None:
    """The same check ``oracle_conformance.rs`` runs on Rust, run on Python."""
    corpus = _load_corpus()
    assert len(corpus["cases"]) == CORPUS_SIZE
    problems = []
    for case in corpus["cases"]:
        result = schedule(Project.from_dict(case["project"]))
        for t in result.tasks:
            got = EngineTask(
                t.early_start,
                t.early_finish,
                t.late_start,
                t.late_finish,
                _whole_days(t.total_float.total_seconds()),
                _whole_days(t.free_float.total_seconds()),
                t.is_critical,
                t.milestone_at_day_end,
            )
            problems += [
                f"{case['name']}/{t.id}: {p}"
                for p in _corpus_row_mismatches(case["expected"][t.id], got)
            ]
    assert not problems, "\n".join(problems)
