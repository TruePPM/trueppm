def engine_milestone_position(task: EngineTask, ref: RefResult, cal: RefCalendar) -> int:
    """Working-time position of an engine milestone's shown early date.

    A milestone shown at the end of day ``D`` sits at the midnight closing ``D``;
    shown at the start of ``D``, at the midnight opening it (#4178, #4207).
    """
    instant = task.early_start + timedelta(days=1 if task.milestone_at_day_end else 0)
    return position_of(instant, ref.project_start_at, cal)


def mismatches(engine: dict[str, EngineTask], ref: RefResult, project: RefProject) -> list[str]:
    """Every field (in the compared set) where the engine disagrees with the reference."""
    out: list[str] = []
    assert set(engine) == set(ref.tasks)
    for tid, want in sorted(ref.tasks.items()):
        got = engine[tid]
        cal = project.calendar_of(tid)  # a milestone's position is read on its own week
        if want.is_milestone:
            have = engine_milestone_position(got, ref, cal)
            need = milestone_shown_position(want, ref, cal)
            if have != need:
                out.append(
                    f"{tid}: milestone position {have} (shown {got.early_start}, "
                    f"at_day_end={got.milestone_at_day_end}), reference {need}"
                )
            continue
        pairs = [
            ("early_start", got.early_start, want.early_start),
            ("early_finish", got.early_finish, want.early_finish),
        ]
        if want.late_stated:
            pairs += [
                ("late_start", got.late_start, want.late_start),
                ("late_finish", got.late_finish, want.late_finish),
                ("total_float", got.total_float, want.total_float),
                ("is_critical", got.is_critical, want.is_critical),
                ("free_float", got.free_float, want.free_float),
            ]
        out.extend(f"{tid}: {name} {g} != reference {w}" for name, g, w in pairs if g != w)
    return out


def assert_matches_reference(engine: dict[str, EngineTask], project: RefProject) -> None:
    ref = reference_schedule(project)
    problems = mismatches(engine, ref, project)
    assert not problems, "\n".join([repr(project), *problems])


