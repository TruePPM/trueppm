def _project_finish(
    project: RefProject,
    early: dict[str, Span],
    shown: dict[str, date],
    project_start: date,
    reads_start: dict[str, bool],
) -> tuple[date, bool]:
    """The project finish instant, and whether work alone decides it.

    The finish is the furthest working-time position any task reaches (a milestone
    placed before the project start counts as the project start). When work
    finishes there, it is the midnight closing that work's last day. When a
    milestone decides it — alone, or lagged into the non-working time after that
    day — how far anything may slip depends on the edge of the day the milestone
    is *shown* on (#4174, #4183), which this oracle does not model, so the caller
    states no late dates in that case.

    A milestone read at the start of a day is shown at the start of the next day
    *its own* calendar works, and that is where it sits against the finish: a
    Monday-to-Friday milestone at Saturday midnight is shown at the start of
    Monday, past seven-day work ending on the Sunday. Marking it at the raw
    Saturday instant let work "decide" a finish the milestone decides, and stated
    late dates for a start-of-day finish this oracle does not model (#4436).
    """
    cal = project.calendar
    work = [early[t][1] for t in project.durations if not is_instant(project, t)]
    marks = [
        start_at_or_after(shown[t], project.calendar_of(t)) if reads_start[t] else shown[t]
        for t in project.durations
        if is_instant(project, t)
    ]
    finish = max(work + marks)
    furthest = position_of(finish, project_start, cal)
    by_work = [i for i in work if position_of(i, project_start, cal) == furthest]
    return finish, bool(by_work) and max(by_work) == finish


def _sf_linked(project: RefProject, tid: str) -> bool:
    """Has ``tid`` an SF link? Its project-start floor is ``min(start, SF placement)``,
    which never binds, so it has none (#4218, #4220)."""
    return any(link.kind == "SF" for link in incoming(project, tid))


def _shown_instant(project: RefProject, tid: str, raw: date) -> date:
    """Where a live milestone is shown: its raw instant, but never before the project
    start (#4225) — unless it has an SF link, which lifts the floor (#4218, #4220)."""
    if _sf_linked(project, tid):
        return raw
    return max(raw, start_at_or_after(project.start, project.calendar_of(tid)))


def _feeds_a_milestone(project: RefProject, tid: str) -> bool:
    """Does any milestone lie downstream of ``tid`` (or is ``tid`` one)?"""
    frontier, seen = [tid], set()
    while frontier:
        current = frontier.pop()
        if is_instant(project, current):
            return True
        seen.add(current)
        frontier += [ln.succ for ln in outgoing(project, current) if ln.succ not in seen]
    return False


def _same_calendar(project: RefProject, link: RefLink) -> bool:
    return project.calendar_of(link.pred) == project.calendar_of(link.succ)


class SummaryRefused(ValueError):
    """The documented summary-expansion rules refuse this input (``reason`` says why)."""

    def __init__(self, reason: str) -> None:
        super().__init__(f"reference summary expansion: {reason}")
        self.reason = reason


def summary_leaves(node: str, children: dict[str, tuple[str, ...]]) -> frozenset[str]:
    """The leaf tasks under ``node``: itself when it is not a summary."""
    if node not in children:
        return frozenset({node})
    return frozenset().union(*(summary_leaves(c, children) for c in children[node]))


def expand_summaries(
    project: RefProject,
    children: dict[str, tuple[str, ...]],
    summary_links: tuple[RefLink, ...],
) -> RefProject:
    """The leaf network a project with summary tasks schedules as (ADR-0024, #4684).

    Written from the documented contract of ``expand_summary_dependencies``, not its
    code. ``project`` holds the leaf tasks and the links between them;
    ``summary_links`` are the links with a summary at either end, and ``children``
    maps each summary to its direct children. Each such link fans out to every
    (predecessor leaf, successor leaf) pair, keeping its type and lag. Links that
    land on one leaf pair merge: one type keeps the largest lag, which is the most
    binding; two types are refused (#4434). A link whose ends share a leaf (a summary
    linked to itself, a descendant or an ancestor) is a cycle (#4705, #4538), as is
    any cycle in the expanded network. ADR-0370 refuses the links whose summary end
    anchors on one leaf rather than every leaf: SS or SF *from* a summary (its start
    is its earliest leaf) and FF or SF *into* one (its finish is its latest, #4437).
    Summaries are absent from the result, which the reference schedules like any
    other network.
    """
    by_pair: dict[tuple[str, str], RefLink] = {(lk.pred, lk.succ): lk for lk in project.links}
    for link in summary_links:
        if link.pred in children and link.kind in ("SS", "SF"):
            raise SummaryRefused("start-side link from a summary")
        if link.succ in children and link.kind in ("FF", "SF"):
            raise SummaryRefused("finish-side link into a summary")
        preds = summary_leaves(link.pred, children)
        succs = summary_leaves(link.succ, children)
        if preds & succs:
            raise SummaryRefused("cycle")
        for p in sorted(preds):
            for s in sorted(succs):
                prior = by_pair.get((p, s))
                if prior is not None and prior.kind != link.kind:
                    raise SummaryRefused("conflicting link types on one leaf pair")
                if prior is None or link.lag > prior.lag:
                    by_pair[(p, s)] = RefLink(p, s, link.kind, link.lag)
    expanded = RefProject(
        start=project.start,
        durations=project.durations,
        links=tuple(by_pair[k] for k in sorted(by_pair)),
        calendar=project.calendar,
        status_date=project.status_date,
        planned_start=project.planned_start,
        progress=project.progress,
        calendars=project.calendars,
        task_calendar=project.task_calendar,
    )
    try:
        topological_order(expanded)
    except ValueError:
        raise SummaryRefused("cycle") from None
    return expanded


def _check_modeled(project: RefProject) -> None:
    """Refuse the inputs this oracle does not model rather than answer them wrongly."""
    for link in project.links:
        if link.kind in ("FF", "SF") and not _same_calendar(project, link):
            raise NotImplementedError(
                "reference CPM: an FF or SF link between tasks on different calendars "
                "is not modeled; which calendar reads its anchor and snaps its finish "
                "is not documented"
            )


def reference_schedule(project: RefProject) -> RefResult:
    """Run the reference forward pass, backward pass, and float computation."""
    _check_modeled(project)
    cal = project.calendar
    order = topological_order(project)
    project_start = start_at_or_after(project.start, cal)

    early: dict[str, Span] = {}
    links_from: dict[str, Span] = {}
    shown: dict[str, date] = {}
    reads_start: dict[str, bool] = {}
    for tid in order:
        if is_complete(project, tid):
            early[tid], start = _pinned(project, tid)
            links_from[tid] = (start, early[tid][1] if project.durations[tid] else start)
            if project.durations[tid] == 0:
                shown[tid] = early[tid][0]
                reads_start[tid] = True  # the start of its pinned day
            continue
        if is_instant(project, tid):
            instant, link, reads_start[tid] = _place_live_milestone(
                project, tid, links_from, reads_start
            )
            early[tid] = (instant, instant)
            links_from[tid] = (link, link)
            shown[tid] = _shown_instant(project, tid, instant)
            continue
        early[tid] = _forward_task(project, tid, early, links_from)
        links_from[tid] = (link_start(project, tid, early[tid]), early[tid][1])

    project_finish, finish_by_work = _project_finish(
        project, early, shown, project_start, reads_start
    )

    late: dict[str, Span] = {}
    for tid in reversed(order):
        if is_complete(project, tid):
            late[tid] = early[tid]  # done: no slack, and no bound on its predecessors
        else:
            late[tid] = _backward_task(project, tid, early[tid], late, project_finish)

    tasks: dict[str, RefTask] = {}
    for tid in order:
        own = project.calendar_of(tid)
        total = working_days_between(early[tid][0], late[tid][0], own)
        n = project.durations[tid]
        complete = is_complete(project, tid)
        stated = complete or (finish_by_work and not _feeds_a_milestone(project, tid))
        if complete:
            free: int | None = 0
        else:
            free = _free_float(project, tid, early, total) if stated else None
        tasks[tid] = RefTask(
            id=tid,
            duration=n,
            start_at=early[tid][0],
            finish_at=early[tid][1],
            late_start_at=late[tid][0],
            late_finish_at=late[tid][1],
            total_float=total,
            free_float=free,
            late_stated=stated,
            complete=complete,
            shown_at=shown.get(tid, early[tid][0]),
            no_remaining=no_remaining(project, tid),
        )
    return RefResult(tasks=tasks, project_start_at=project_start, project_finish_at=project_finish)


def milestone_shown_position(task: RefTask, result: RefResult, cal: RefCalendar) -> int:
    """Working-time position at which a milestone is shown."""
    assert task.shown_at is not None
    return position_of(task.shown_at, result.project_start_at, cal)
