"""A slow, obvious reference CPM pass — a test oracle, not a third engine (#3987).

The two production engines (``trueppm_scheduler.engine`` in Python and
``packages/wasm-scheduler`` in Rust) were only ever checked against each other,
through snapshots generated by the Python one. That proves they agree, not that
either is right. This module is written from the CPM math and the *documented*
conventions (``README.md`` "Conventions", the website's Scheduler Conventions and
CPM Scheduler pages), so a property that holds ``engine == reference`` is
evidence of correctness rather than of parity.

"Written from the documented conventions" is not the same claim as "written
without ever looking at engine behavior" — a handful of rules were
underspecified or contradicted by the docs, and for those the choice below was
calibrated against what the engines actually do, not derived from prose alone:
the SF-only milestone floor (lands on the documented rule, #4218, once read
against engine output), the zero-lag FF finish instant
(:func:`finish_meeting`), and the lead (negative lag) snap direction — see the
note on that bullet below. The lead snap direction was the one place the docs
disagreed with both engines (#4274); the docs were wrong and have been
corrected to match the engines, which is what this module already modeled.
The SF zero-lag anchor (#4145) was calibrated the same way until #4322, which
checked it against a real MS-Project-saved schedule
(``tests/fixtures/msproject/link_types_2013.py``) and found it matches; it is
no longer a calibrated-only rule, though the SF-only milestone floor still is.
Every other rule is read from the docs alone.

It deliberately imports nothing from ``trueppm_scheduler``: its input is plain
data (:class:`RefProject`) and its output is plain data (:class:`RefTask`).

Legibility beats speed everywhere. Every calendar question is answered by walking
one day at a time, and the backward pass and free float are found by *search* —
slide the task later one step at a time until a link would break — rather than by
inverting the forward formulas. That makes the two directions consistent by
construction: they share one definition of "this link is satisfied".

The time model
--------------
Time is a line of **midnights**. A ``date`` ``m`` used as an *instant* means "the
midnight at the start of ``m``". Working day ``d`` occupies ``[d, d + 1 day)``, so:

* a task of ``n >= 1`` working days starts at the midnight *opening* its first
  working day and finishes at the midnight *closing* its last one;
* its shown ``early_start`` is that first day and its shown ``early_finish`` is the
  last working day, ``finish_instant - 1 day``;
* a zero-duration milestone is a single raw instant, which may be any midnight —
  including one inside a weekend.

The **working-time position** of an instant is the number of working days before
it. The end of a Friday and the start of the next Monday are the same position.
Every float is a difference of positions.

Documented rules modeled
------------------------
* Durations count working days; a lag counts **calendar** days added to the
  link's anchor, and the resulting date snaps forward to a working day (README,
  "Duration and lag are counted in different units"; #2534). This snaps
  **forward** for a lead (negative lag) too, which is what both engines do and
  what the docs now say (#4274 decided the docs, not the engines, were wrong).
* Anchors: FS and FF anchor on the predecessor's finish (the midnight closing its
  last working day); SS on its start (the midnight opening its first working day);
  SF on its start *read as a finish* — the midnight closing the working day
  before it — which is what puts a zero-lag SF successor's last working day on
  the working day before the predecessor starts (#4145). A positive SF lag counts
  from the start itself instead, as an FF lag counts from the finish (#4333). A
  milestone anchors on its raw instant (SF with no lag or a lead: read back to the
  closing of the last working day).
* FS/SS constrain the successor's start: it is the first working-day start at or
  after ``anchor + lag``. FF/SF constrain its finish: with a lag, the end of the
  first working day on or after the day ``anchor + lag`` closes; with no lag there
  is no date to snap, so it only has to reach ``anchor`` in working time; a lead
  counts back from that zero-lag finish, so the finish is monotone in the lag
  (#4273). A task
  stays contiguous; a finish link that pins it later than its start links allow
  right-aligns it on that finish (#3806). A milestone successor is the raw latest
  of everything its links require.
* Every task's project-start floor (snapped forward to a working day) is
  ``min(project start, SF placement)`` (#4218, #4220). A task with no SF link has
  no SF placement and takes the project start; a task with one is already held at
  or after its SF placement by that link, so the floor never binds and is left
  out. A milestone's raw instant is never floored — the project start only bounds
  the day it is *shown* on (#4225), and not even that for a milestone with an SF
  link; with no links it sits at the project start.
* The project finish is the latest (shown) finish; nothing may finish after it.
  ``total_float`` is the working days from early start to late start;
  ``free_float`` is the largest working-day slip that keeps every successor's
  link satisfied at that successor's early dates, capped at total float, and equal
  to total float for a task with no successor (#1828).

Progress rules modeled (ADR-0132, ADR-0136; #4633)
---------------------------------------------------
* **Per-task calendars.** Each task's durations, floors and float are counted on
  its own calendar (:meth:`RefProject.calendar_of`). A link's anchor is read on the
  predecessor's calendar and its successor's requirement snapped on the
  successor's.
* **Floors.** Live work and live milestones are floored at the data date and at
  an SNET (``planned_start``), each snapped to a working-day start on the task's
  own calendar, and at the project start as above. A data date or SNET that snaps
  to a day at or before the project start is no floor at all (#4635, the package
  README): it is the project-start floor, which an SF-linked task and a milestone's
  link instant do not take. A recorded ``actual_start`` is
  a floor kept **verbatim**, even on a non-working day; when it is the latest
  floor the task's window opens there and its first working day is the one after
  (#4332).
* **Remaining duration.** Live work at ``p`` percent schedules only its remaining
  ``n - floor(n * p / 100)`` working days (ADR-0132 §3): its early and late dates
  are that remaining window.
* **Start-side links (ADR-0132 §2a).** SS and SF links out of live work measure
  from its *link start*: its recorded ``actual_start``; else, with elapsed work,
  its derived span start (the full duration backed off its early finish); else
  its early start. A link measured from a **recorded** start is history: it bounds
  neither the predecessor's late dates nor its free float. One measured from a
  derived start keeps its bound, slipping with the remaining window.
* **Completed work is pinned (ADR-0136).** A task with ``actual_finish`` or at
  100% keeps its full duration, laid out from whatever actuals exist (both: the
  actuals verbatim; one: the other end derived), or with none from the project
  start or a later SNET, never from its predecessors or the data date. Its late
  dates equal its early ones, its floats are 0, and it is never critical. A link
  *into* completed work bounds nothing: its predecessor's late dates and free
  float ignore it.
* **Completed milestones** with no actuals are an instant at the start of the
  pinned day — the later of the project start and their SNET — and are linked
  from that instant (#4343, #4225, #4635).
* **Late dates never precede early ones (#3963).** The backward search is floored
  at the early span. This is modeled but not discriminated: the search already
  stops at or after the early span, so no generated or pinned case makes the
  floor bind, and a mutation removing it (here or in the Python engine) survives
  every property (see :func:`_backward_task`).

Not modeled, and refused by :func:`reference_schedule` rather than answered:

* an FF or SF link between two tasks on different calendars — which calendar
  reads its zero-lag close and snaps its finish is not documented, and the
  engines' choice is not one the docs let this module derive;
* a completed milestone with recorded actuals, which keeps the day edge it had
  live (#4433, #4525) — a display convention this oracle does not model.

Out of scope: summary tasks, ``live_day_end_on``, Monte Carlo. One shape is
modeled but excluded from the engine comparison by name: an FF link out of
completed work whose ``actual_finish`` is a non-working day, which this module
reads in working time and both engines read as the verbatim day (#4631, open;
``_ff_out_of_a_non_working_actual_finish`` in ``test_cpm_oracle.py``).

For a milestone the oracle states only *where in working time* it sits. Which of
two adjacent days it is *shown* on is a display convention (#4079, #4173, #4183)
it does not model, and float is read from that shown day, so the oracle states no
late dates or floats (``RefTask.late_stated``) for a milestone, for any live task
upstream of one, or for any live task at all when a milestone decides the project
finish. Completed work is always stated: pinned, its late dates are its early
ones whatever the finish.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date, timedelta

ONE_DAY = timedelta(days=1)
LINK_TYPES = ("FS", "SS", "FF", "SF")

# Bit 0 = Monday ... bit 6 = Sunday (the documented ``Calendar.working_days`` mask).
MON_TO_FRI = 0b0011111

Span = tuple[date, date]  # (start instant, finish instant)


@dataclass(frozen=True)
class RefCalendar:
    working_mask: int = MON_TO_FRI
    exceptions: tuple[tuple[date, date], ...] = ()  # inclusive non-working ranges

    def is_working(self, day: date) -> bool:
        if not (self.working_mask >> day.weekday()) & 1:
            return False
        return not any(lo <= day <= hi for lo, hi in self.exceptions)


@dataclass(frozen=True)
class RefLink:
    pred: str
    succ: str
    kind: str  # one of LINK_TYPES
    lag: int  # calendar days, may be negative


@dataclass(frozen=True)
class RefProgress:
    """A task's recorded progress (ADR-0132/0136): plain input data."""

    percent_complete: float = 0.0
    actual_start: date | None = None
    actual_finish: date | None = None

    @property
    def complete(self) -> bool:
        """``actual_finish`` recorded, or ``percent_complete`` at 100 (ADR-0136)."""
        return self.actual_finish is not None or self.percent_complete >= 100


@dataclass(frozen=True)
class RefProject:
    start: date
    durations: dict[str, int]  # task id -> working days (0 = milestone)
    links: tuple[RefLink, ...]
    calendar: RefCalendar = RefCalendar()
    # Progress-era inputs (#4439). All default to "absent", and a project that sets
    # none of them is the pure planning network every earlier case is.
    status_date: date | None = None  # the data date
    planned_start: dict[str, date] = field(default_factory=dict)  # SNET, per task
    progress: dict[str, RefProgress] = field(default_factory=dict)
    calendars: dict[str, RefCalendar] = field(default_factory=dict)  # per-task registry
    task_calendar: dict[str, str] = field(default_factory=dict)  # task id -> registry id

    def calendar_of(self, tid: str) -> RefCalendar:
        """The calendar ``tid`` works on: its registry entry, else the project's."""
        cid = self.task_calendar.get(tid)
        return self.calendars[cid] if cid is not None else self.calendar


@dataclass
class RefTask:
    """One task's reference result. All ``*_at`` fields are instants (midnights)."""

    id: str
    duration: int
    start_at: date
    finish_at: date
    late_start_at: date
    late_finish_at: date
    total_float: int
    free_float: int | None  # None when ``late_stated`` is False
    # False when the late dates and floats depend on which edge of its day a
    # milestone is shown on — a display convention the oracle does not model.
    late_stated: bool = True
    # A milestone's shown instant: ``start_at`` floored at the project start.
    shown_at: date | None = None
    # Completed (ADR-0136): pinned, zero float, never critical.
    complete: bool = False

    @property
    def is_critical(self) -> bool:
        return self.total_float == 0 and not self.complete

    @property
    def is_milestone(self) -> bool:
        return self.duration == 0

    @property
    def early_start(self) -> date:
        return self.start_at

    @property
    def early_finish(self) -> date:
        """The shown finish day of a task with work: its last working day."""
        return self.finish_at - ONE_DAY

    @property
    def late_start(self) -> date:
        return self.late_start_at

    @property
    def late_finish(self) -> date:
        return self.late_finish_at - ONE_DAY


@dataclass
class RefResult:
    tasks: dict[str, RefTask]
    project_start_at: date
    project_finish_at: date


# ---------------------------------------------------------------------------
# Calendar walking — one day at a time, on purpose.
# ---------------------------------------------------------------------------


def first_working_on_or_after(day: date, cal: RefCalendar) -> date:
    while not cal.is_working(day):
        day += ONE_DAY
    return day


def last_working_on_or_before(day: date, cal: RefCalendar) -> date:
    while not cal.is_working(day):
        day -= ONE_DAY
    return day


def working_days_between(a: date, b: date, cal: RefCalendar) -> int:
    """Signed count of working days in ``[a, b)``: position(b) - position(a)."""
    if b < a:
        return -working_days_between(b, a, cal)
    count = 0
    day = a
    while day < b:
        count += cal.is_working(day)
        day += ONE_DAY
    return count


def position_of(instant: date, origin: date, cal: RefCalendar) -> int:
    """Working-time position of an instant, relative to ``origin``."""
    return working_days_between(origin, instant, cal)


def start_at_or_after(instant: date, cal: RefCalendar) -> date:
    """Earliest working-day start (the midnight opening a working day) >= ``instant``."""
    return first_working_on_or_after(instant, cal)


def end_on_or_after_day_closed_by(instant: date, cal: RefCalendar) -> date:
    """The end of the first working day on or after the day ``instant`` closes."""
    return first_working_on_or_after(instant - ONE_DAY, cal) + ONE_DAY


def close_of_previous_working_day(instant: date, cal: RefCalendar) -> date:
    """The latest working-day end (midnight closing a working day) <= ``instant``."""
    return last_working_on_or_before(instant - ONE_DAY, cal) + ONE_DAY


def finish_from_start(start: date, n: int, cal: RefCalendar) -> date:
    """End instant of ``n`` working days beginning at working-day start ``start``."""
    day, left = start, n
    while True:
        if cal.is_working(day):
            left -= 1
            if left == 0:
                return day + ONE_DAY
        day += ONE_DAY


def start_from_finish(finish: date, n: int, cal: RefCalendar) -> date:
    """Start instant of ``n`` working days ending at working-day end ``finish``."""
    day, left = finish - ONE_DAY, n
    while True:
        if cal.is_working(day):
            left -= 1
            if left == 0:
                return day
        day -= ONE_DAY


def next_working_start(start: date, cal: RefCalendar) -> date:
    return first_working_on_or_after(start + ONE_DAY, cal)


def previous_working_start(start: date, cal: RefCalendar) -> date:
    return last_working_on_or_before(start - ONE_DAY, cal)


# ---------------------------------------------------------------------------
# One link: what it needs of its successor, and whether a placement satisfies it
# ---------------------------------------------------------------------------


def link_need(link: RefLink, pred: Span, cal: RefCalendar) -> date:
    """The raw instant ``link`` requires its successor's start/finish to reach."""
    pred_start, pred_finish = pred
    if link.kind in ("FS", "FF"):
        anchor = pred_finish
    elif link.kind == "SS":
        anchor = pred_start
    elif link.lag > 0:
        # SF with a positive lag counts from the start instant itself (#4333), as
        # FF does from a finish: the end of the day before ``need`` is snapped by
        # :func:`finish_meeting`, not pre-snapped here, or a weekend between the
        # last working day and the start absorbs the lag.
        anchor = pred_start
    else:  # SF: the predecessor's start, read as the finish of the day before it
        anchor = close_of_previous_working_day(pred_start, cal)
    return anchor + timedelta(days=link.lag)


def constrains_start(link: RefLink) -> bool:
    return link.kind in ("FS", "SS")


def finish_meeting(link: RefLink, need: date, cal: RefCalendar) -> date:
    """The earliest finish of a task with work that meets an FF/SF ``need``.

    With a lag, the lagged date snaps forward to a working day (#2534): the task
    ends with the first working day on or after the day ``need`` closes. With no
    lag there is no date arithmetic to snap — the finish only has to reach
    ``need`` in working time, which the end of the last working day before it does.

    A lead counts back from that zero-lag finish, not from the raw anchor, so the
    finish is monotone in the lag (#4273). The two differ only for an anchor just
    after non-working time — a milestone at the start of Monday: counted from the
    instant, a one-day lead names Saturday and snaps forward to Monday, *later*
    than zero lag's Friday; counted from Friday it reaches Thursday. For a task
    with work the anchor already closes a working day, so they agree; an SF lead's
    anchor is that zero-lag close already (:func:`link_need`).
    """
    if link.lag == 0:
        return close_of_previous_working_day(need, cal)
    if link.lag < 0:
        anchor = need - timedelta(days=link.lag)
        need = close_of_previous_working_day(anchor, cal) + timedelta(days=link.lag)
    return end_on_or_after_day_closed_by(need, cal)


def link_holds(
    link: RefLink,
    pred: Span,
    succ: Span,
    succ_is_milestone: bool,
    pred_cal: RefCalendar,
    succ_cal: RefCalendar | None = None,
) -> bool:
    """Is ``link`` satisfied with the predecessor at ``pred`` and successor at ``succ``?

    ``pred`` is the span the predecessor's links measure from (its link start and
    finish). The successor's own calendar snaps what it needs; a successor start on
    a non-working day — a recorded actual start, kept verbatim — is the working day
    after it (#4332).
    """
    cal = pred_cal if succ_cal is None else succ_cal
    need = link_need(link, pred, pred_cal)
    succ_start, succ_finish = succ
    if succ_is_milestone:
        return need <= succ_start
    if constrains_start(link):
        return start_at_or_after(need, cal) <= start_at_or_after(succ_start, cal)
    return finish_meeting(link, need, cal) <= succ_finish


# ---------------------------------------------------------------------------
# Graph order
# ---------------------------------------------------------------------------


def topological_order(project: RefProject) -> list[str]:
    """Kahn's algorithm, ties broken by id so the order is deterministic."""
    indegree = dict.fromkeys(project.durations, 0)
    for link in project.links:
        indegree[link.succ] += 1
    ready = sorted(t for t, d in indegree.items() if d == 0)
    order: list[str] = []
    while ready:
        tid = ready.pop(0)
        order.append(tid)
        for link in project.links:
            if link.pred == tid:
                indegree[link.succ] -= 1
                if indegree[link.succ] == 0:
                    ready.append(link.succ)
                    ready.sort()
    if len(order) != len(project.durations):
        raise ValueError("reference CPM: the network has a cycle")
    return order


def incoming(project: RefProject, tid: str) -> list[RefLink]:
    return [link for link in project.links if link.succ == tid]


def outgoing(project: RefProject, tid: str) -> list[RefLink]:
    return [link for link in project.links if link.pred == tid]


# ---------------------------------------------------------------------------
# Progress (ADR-0132, ADR-0136): what a task's recorded progress does to it
# ---------------------------------------------------------------------------


def _progress(project: RefProject, tid: str) -> RefProgress:
    return project.progress.get(tid, RefProgress())


def is_complete(project: RefProject, tid: str) -> bool:
    """Completed work is pinned at its actuals and leaves network logic (ADR-0136)."""
    return _progress(project, tid).complete


def remaining_days(project: RefProject, tid: str) -> int:
    """Working days of live work still to do: ``n - floor(n * pct / 100)`` (ADR-0132 §3)."""
    n = project.durations[tid]
    pct = _progress(project, tid).percent_complete
    return n - int(n * pct / 100) if pct > 0 else n


def _start_is_recorded(project: RefProject, tid: str) -> bool:
    """Live work with an ``actual_start``: its start already happened (ADR-0132 §2a)."""
    return (
        project.durations[tid] > 0
        and not is_complete(project, tid)
        and _progress(project, tid).actual_start is not None
    )


def link_start(project: RefProject, tid: str, span: Span) -> date:
    """The start an SS or SF link out of ``tid`` measures from (ADR-0132 §2a).

    The recorded ``actual_start`` of live work; for live work with elapsed days but
    no recorded start, the full duration backed off from its finish (the derived
    span start); otherwise the start of ``span`` itself.
    """
    if _start_is_recorded(project, tid):
        recorded = _progress(project, tid).actual_start
        assert recorded is not None
        return recorded
    n = project.durations[tid]
    if n > 0 and not is_complete(project, tid) and remaining_days(project, tid) < n:
        return start_from_finish(span[1], n, project.calendar_of(tid))
    return span[0]


def _start_fixed(project: RefProject, link: RefLink) -> bool:
    """An SS/SF link measured from a recorded start: no slip of the predecessor's
    remaining work moves its successor through it, so it bounds neither the
    predecessor's late dates nor its free float (ADR-0132 §2a).

    In this search-based model the exclusion is also true by construction — a link
    measured from a constant recorded start holds at every candidate slip — so
    dropping it changes no answer here. The engines compute the bound by formula,
    where keeping it does (it floors the late window at the early one and reports
    slack work critical), and the engine-side mutation is caught."""
    return link.kind in ("SS", "SF") and _start_is_recorded(project, link.pred)


def _pinned(project: RefProject, tid: str) -> tuple[Span, date]:
    """A completed task's span and the instant its links measure from (ADR-0136).

    Work spans its full duration from whatever actuals exist, a missing end derived
    from the other; with none, it is laid out from the project start (or a later
    SNET), never the data date — completed work is history. A completed milestone
    with no actuals is an instant at the start of that day, and its links measure
    from its SNET when one is set (#4343, #4225).
    """
    cal = project.calendar_of(tid)
    n = project.durations[tid]
    recorded = _progress(project, tid)
    base = start_at_or_after(project.start, cal)
    snet = project.planned_start.get(tid)
    if n == 0:
        if recorded.actual_start is not None or recorded.actual_finish is not None:
            raise NotImplementedError(
                "reference CPM: a completed milestone with recorded actuals keeps the "
                "day edge it had live (#4433, #4525), which this oracle does not model"
            )
        # An SNET at or before the start is no floor (#4635): link from the shown day.
        shown = base if snet is None else max(base, start_at_or_after(snet, cal))
        return (shown, shown), shown
    if recorded.actual_finish is not None:
        finish = recorded.actual_finish + ONE_DAY
        start = recorded.actual_start or start_from_finish(finish, n, cal)
        return (start, finish), start
    if recorded.actual_start is not None:
        start = recorded.actual_start
        return (start, finish_from_start(start, n, cal)), start
    start = base if snet is None else max(base, start_at_or_after(snet, cal))
    return (start, finish_from_start(start, n, cal)), start


# ---------------------------------------------------------------------------
# Forward pass
# ---------------------------------------------------------------------------


def _needs(
    project: RefProject, tid: str, links_from: dict[str, Span]
) -> list[tuple[RefLink, date]]:
    """Each incoming link and the raw instant it requires of ``tid``.

    ``links_from`` holds, per placed task, the span its links measure from: its link
    start (:func:`link_start`) and its finish — for a milestone, its link instant.
    """
    return [
        (link, link_need(link, links_from[link.pred], project.calendar_of(link.pred)))
        for link in incoming(project, tid)
    ]


def _snapped_floors(project: RefProject, tid: str) -> list[date]:
    """The floors that bind ``tid`` beyond the project start and its actual start: the
    data date and an SNET, each the start of a working day on its own calendar, and
    each only when that day is after the project start's (#4635)."""
    cal = project.calendar_of(tid)
    base = start_at_or_after(project.start, cal)
    raw = [project.status_date, project.planned_start.get(tid)]
    snapped = [start_at_or_after(d, cal) for d in raw if d is not None]
    return [d for d in snapped if d > base]


def _forward_task(
    project: RefProject, tid: str, early: dict[str, Span], links_from: dict[str, Span]
) -> Span:
    """Early span of one live task, its predecessors already placed.

    For live work it is the window of its *remaining* days (ADR-0132). A recorded
    actual start is a floor kept verbatim, even on a non-working day; the other
    floors are the start of a working day.
    """
    cal = project.calendar_of(tid)
    needs = _needs(project, tid, links_from)

    recorded = _progress(project, tid).actual_start
    floors = _snapped_floors(project, tid)

    if project.durations[tid] == 0:
        # A milestone is one raw instant: the latest of everything that holds it.
        held = [need for _, need in needs] + floors
        if recorded is not None:
            held.append(recorded)
        instant = max(held) if held else start_at_or_after(project.start, cal)
        return instant, instant

    n = remaining_days(project, tid)
    start_needs = [need for link, need in needs if constrains_start(link)] + floors
    if not _sf_linked(project, tid):
        start_needs.append(project.start)

    finishes = [
        finish_meeting(link, need, cal) for link, need in needs if not constrains_start(link)
    ]
    start: date | None = None
    if start_needs or recorded is not None:
        snapped = [start_at_or_after(max(start_needs), cal)] if start_needs else []
        start = max(snapped + ([recorded] if recorded is not None else []))
        finishes.append(finish_from_start(start, n, cal))
    finish = max(finishes)  # non-empty: a floor, or at least one SF link
    if start is not None and finish == finish_from_start(start, n, cal):
        return start, finish
    return start_from_finish(finish, n, cal), finish


# ---------------------------------------------------------------------------
# Backward pass (by search) and free float (by search)
