def _needs(
    project: RefProject, tid: str, links_from: dict[str, Span]
) -> list[tuple[RefLink, date]]:
    """Each incoming link and the raw instant it requires of ``tid``.

    ``links_from`` holds, per placed task, the span its links measure from: its link
    start (:func:`link_start`) and its finish — for a milestone, its link instant.
    """
    return [
        (
            link,
            link_need(
                link,
                pred_span(project, link, links_from[link.pred]),
                project.calendar_of(link.pred),
            ),
        )
        for link in incoming(project, tid)
    ]


def _snapped_floors(project: RefProject, tid: str) -> list[date]:
    """The floors that bind ``tid`` beyond the project start and its actual start: the
    data date and an SNET, each the start of a working day on its own calendar. The
    data date binds only when that day is after the project start's, and so does the
    SNET of a task with no SF link (#4635)."""
    cal = project.calendar_of(tid)
    base = start_at_or_after(project.start, cal)
    out = []
    if project.status_date is not None:
        data_date = start_at_or_after(project.status_date, cal)
        if data_date > base:
            out.append(data_date)
    if tid in project.planned_start:
        snet = start_at_or_after(project.planned_start[tid], cal)
        if snet > base or _sf_linked(project, tid):
            out.append(snet)
    return out


def _proposal_reads_start(
    project: RefProject, link: RefLink, need: date, reads_start: dict[str, bool]
) -> bool:
    """Whether the instant ``link`` proposes to a milestone is shown as a day start.

    The Scheduler Conventions milestone row: a milestone driven by work sits at the
    end of its driver's day, and one a lag places after non-working time is shown
    at the start of the next working day (#4173). An SS link reads as a start; a
    zero-lag FS/FF/SS link out of another milestone lands on that milestone's own
    midnight and keeps its reading (#4079). Only :func:`_floor_link` asks.
    """
    if link.kind == "SF":
        base = False
    elif link.lag == 0 and is_instant(project, link.pred) and not detached_link(project, link):
        base = reads_start[link.pred]
    else:
        base = link.kind == "SS"
    return base or not project.calendar_of(link.succ).is_working(need - ONE_DAY)


def detached_link(project: RefProject, link: RefLink) -> bool:
    """An SS/SF link out of a :func:`detached` instant (ADR-1474)."""
    return link.kind in ("SS", "SF") and detached(project, link.pred)


def _floor_link(
    project: RefProject, tid: str, proposal: tuple[date, bool], floor: date
) -> tuple[date, bool] | None:
    """The instant milestone ``tid``, held by ``floor``, links from, or ``None`` (#4690, #4883).

    ``None`` when the latest link ``proposal`` is at or after ``floor``, or when the
    floor has no working-time equivalent before it (the day before it is a working
    day): the link is then the floor.

    Otherwise every midnight from the close of the last working day before
    ``floor`` up to ``floor`` is the same working-time point — on a non-working
    floor (a weekend ``actual_start``, kept verbatim) too, back to the start of the
    non-working run that holds it, so the link never goes backward as the floor
    moves later — and the milestone
    links from the latest of the proposal and that earliest midnight, read as a day
    start. That is the one choice that is non-decreasing in the proposal, so a
    slipping predecessor never moves the successors earlier (#4883). Below the
    project start, when ``floor`` is the project start's day, the proposal keeps its
    own instant (the project start only bounds where a milestone is shown, #4225).
    """
    raw = proposal[0]
    if raw >= floor:
        return None
    cal = project.calendar_of(tid)
    if not _sf_linked(project, tid):
        base = start_at_or_after(project.start, cal)
        if raw < base and base == floor:
            return proposal
    earliest = last_working_on_or_before(floor - ONE_DAY, cal) + ONE_DAY
    if earliest >= floor:
        return None
    return max(raw, earliest), True


def _place_live_milestone(
    project: RefProject, tid: str, links_from: dict[str, Span], reads_start: dict[str, bool]
) -> tuple[date, date, bool]:
    """``(instant, link instant, link reads as a day start)`` of a live milestone.

    The instant is the raw latest of everything that holds it. Its successors
    measure from the same instant, except where a floor holds a linked milestone
    (:func:`_floor_link`): then they measure from the latest of the link's own
    midnight and the floor's earliest working-time equivalent, so recording or
    pinning the day a milestone is shown moves nothing, and a slipping predecessor
    never moves the successors earlier (#4883).
    """
    cal = project.calendar_of(tid)
    proposals = [
        (need, _proposal_reads_start(project, link, need, reads_start))
        for link, need in _needs(project, tid, links_from)
    ]
    floors = _snapped_floors(project, tid)
    recorded = _progress(project, tid).actual_start
    if recorded is not None:
        floors.append(recorded)
    if not proposals and not floors:
        base = start_at_or_after(project.start, cal)
        return base, base, True
    latest = max(proposals) if proposals else None
    floor = max(floors) if floors else None
    if latest is None or (floor is not None and floor >= latest[0]):
        assert floor is not None
        held = (floor, True)
    else:
        held = latest
    link = held
    if latest is not None and floor is not None:
        link = _floor_link(project, tid, latest, floor) or held
    elif floor is not None and floor != start_at_or_after(project.start, cal):
        # Nothing precedes it: the floor holds it outright, and it links from the
        # floor's earliest working-time equivalent midnight, as a floor holding an
        # earlier link does (#5094). Linking from the floor itself let a
        # non-binding predecessor move the successors.
        earliest = last_working_on_or_before(floor - ONE_DAY, cal) + ONE_DAY
        if earliest < floor:
            link = (earliest, True)
    return held[0], link[0], link[1]


def _forward_task(
    project: RefProject, tid: str, early: dict[str, Span], links_from: dict[str, Span]
) -> Span:
    """Early span of one live work task, its predecessors already placed.

    It is the window of its *remaining* days (ADR-0132). A recorded actual start is
    a floor kept verbatim, even on a non-working day; the other floors are the
    start of a working day. Live milestones are :func:`_place_live_milestone`.
    """
    cal = project.calendar_of(tid)
    needs = _needs(project, tid, links_from)

    recorded = _progress(project, tid).actual_start
    floors = _snapped_floors(project, tid)

    n = remaining_days(project, tid)
    start_needs = [need for link, need in needs if constrains_start(link)] + floors
    if not _sf_linked(project, tid):
        start_needs.append(project.start)

    finishes = [
        finish_meeting(link, need, cal) for link, need in needs if not constrains_start(link)
    ]
    start: date | None = None
    if start_needs or recorded is not None:
        snapped = [start_at_or_after(max(start_needs), cal)] if start_needs else []
        start = max(snapped + ([recorded] if recorded is not None else []))
        finishes.append(finish_from_start(start, n, cal))
    finish = max(finishes)  # non-empty: a floor, or at least one SF link
    if start is not None and finish == finish_from_start(start, n, cal):
        return start, finish
    return start_from_finish(finish, n, cal), finish


